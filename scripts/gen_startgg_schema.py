"""Saves start.gg's GraphQL schemas to docs/startgg/ as SDL, so there's a local
copy to read and grep when changing the queries HyperDrive sends.

- schema.graphql: the site's internal API (www.start.gg/api/-/gql), which
  StartGGDataProvider queries. It needs no token.
- public_schema.graphql: the public API (api.start.gg/gql/alpha), which
  StartGGReporter uses. Introspecting it needs a token, so it's only updated
  when STARTGG_TOKEN is set.

Types and fields are sorted, so a diff of either file shows only what start.gg
changed.

Usage: uv run scripts/gen_startgg_schema.py [out_dir]

Run daily by .github/workflows/update_startgg_schema.yml.
"""

import os
import sys

import requests
from graphql import (
    build_client_schema,
    get_introspection_query,
    lexicographic_sort_schema,
    print_schema,
)

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
OUT_DIR = os.path.join(ROOT, "docs", "startgg")

INTERNAL_URL = "https://www.start.gg/api/-/gql"
PUBLIC_URL = "https://api.start.gg/gql/alpha"

# The headers StartGGDataProvider sends to the internal API
INTERNAL_HEADERS = {
    "client-version": "20",
    "Content-Type": "application/json",
    "User-Agent": "Mozilla/5.0 (Linux; Android 6.0; Nexus 5 Build/MRA58N) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/119.0.0.0 Mobile Safari/537.36",
}


def fetch_sdl(url, headers):
    response = requests.post(
        url,
        headers=headers,
        json={"query": get_introspection_query(descriptions=True)},
        timeout=60,
    )
    response.raise_for_status()
    body = response.json()
    if not body.get("data"):
        raise RuntimeError(f"{url} returned no schema: {str(body)[:500]}")

    schema = lexicographic_sort_schema(build_client_schema(body["data"]))
    return print_schema(schema) + "\n"


def write(path, header, sdl):
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(header + "\n" + sdl)
    print(f"Wrote {os.path.relpath(path, ROOT)}")


def main():
    out_dir = sys.argv[1] if len(sys.argv) > 1 else OUT_DIR
    os.makedirs(out_dir, exist_ok=True)

    write(
        os.path.join(out_dir, "schema.graphql"),
        f"# start.gg internal API schema ({INTERNAL_URL}), used by StartGGDataProvider.\n"
        "# Generated by scripts/gen_startgg_schema.py. Don't edit by hand.\n",
        fetch_sdl(INTERNAL_URL, INTERNAL_HEADERS),
    )

    token = os.environ.get("STARTGG_TOKEN")
    if token:
        write(
            os.path.join(out_dir, "public_schema.graphql"),
            f"# start.gg public API schema ({PUBLIC_URL}), used by StartGGReporter.\n"
            "# Generated by scripts/gen_startgg_schema.py. Don't edit by hand.\n",
            fetch_sdl(
                PUBLIC_URL, {"Authorization": f"Bearer {token}", "Content-Type": "application/json"}
            ),
        )
    else:
        print("STARTGG_TOKEN isn't set, skipping the public API schema")


if __name__ == "__main__":
    main()
