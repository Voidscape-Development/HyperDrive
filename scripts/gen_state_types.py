"""Writes layout/include/state.d.ts, the TypeScript types of the program
state, from its description in src/state_schema.py.

Usage, from anywhere:
    python scripts/gen_state_types.py           writes the file
    python scripts/gen_state_types.py --check   fails if the file isn't up to date

Run it after changing src/state_schema.py and commit the result:
test/test_state_schema.py checks that it was.
"""

import importlib.util
import inspect
import json
import os
import re
import sys
import types
import typing

from pydantic import BaseModel

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
SCHEMA_FILE = os.path.join(ROOT, "src", "state_schema.py")
OUT_FILE = os.path.join(ROOT, "layout", "include", "state.d.ts")

NAMESPACE = "HDState"


def load_schema():
    """src/state_schema.py as a module, without importing the application."""
    spec = importlib.util.spec_from_file_location("state_schema", SCHEMA_FILE)
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


def models(schema):
    """The schema's models, in the order they are written."""
    return [
        value
        for value in vars(schema).values()
        if inspect.isclass(value)
        and issubclass(value, schema.StateModel)
        and value is not schema.StateModel
        and value.__module__ == schema.__name__
    ]


def ts_type(annotation, schema):
    """A Python annotation of the schema as a TypeScript type."""
    if annotation is None or annotation is type(None):
        return "null"
    if annotation is typing.Any:
        return "any"
    if annotation is bool:
        return "boolean"
    if annotation in (int, float):
        return "number"
    if annotation is str:
        return "string"
    if inspect.isclass(annotation) and issubclass(annotation, BaseModel):
        return annotation.__name__

    origin = typing.get_origin(annotation)
    args = typing.get_args(annotation)
    if origin is typing.Annotated:
        if schema.LooseMarker in args[1:]:
            return "Loose"
        return ts_type(args[0], schema)
    if origin in (typing.Union, types.UnionType):
        parts = []
        for arg in args:
            part = ts_type(arg, schema)
            if part == "any":
                return "any"
            if part not in parts:
                parts.append(part)
        # null last
        parts.sort(key=lambda part: part == "null")
        return " | ".join(parts)
    if origin is typing.Literal:
        return " | ".join(json.dumps(arg) for arg in args)
    if origin is list:
        item = ts_type(args[0], schema)
        return f"({item})[]" if " " in item and not item.startswith("Record<") else f"{item}[]"
    if origin is dict:
        if args[0] is not str:
            raise TypeError(f"Keys of JSON objects are text: {annotation!r}")
        return f"Record<string, {ts_type(args[1], schema)}>"
    raise TypeError(f"No TypeScript type for {annotation!r}")


def comment(text, indent):
    """A doc comment, or nothing."""
    lines = [line.strip() for line in inspect.cleandoc(text or "").splitlines()]
    while lines and not lines[-1]:
        lines.pop()
    if not lines:
        return []
    if len(lines) == 1:
        return [f"{indent}/** {lines[0]} */"]
    return [f"{indent}/**", *[f"{indent} * {line}".rstrip() for line in lines], f"{indent} */"]


def interface(model, schema):
    lines = comment(model.__doc__ if model.__doc__ != schema.StateModel.__doc__ else "", "  ")
    lines.append(f"  interface {model.__name__} {{")
    for name, field in model.model_fields.items():
        key = field.alias or name
        if not re.fullmatch(r"[A-Za-z_$][A-Za-z0-9_$]*", key):
            key = json.dumps(key)
        lines += comment(field.description, "    ")
        # The annotation as written, Annotated kept
        annotation = typing.get_type_hints(model, include_extras=True)[name]
        lines.append(f"    {key}?: {ts_type(annotation, schema)};")
    extra = typing.get_type_hints(model, include_extras=True).get("__pydantic_extra__")
    if extra is not None and model.__annotations__.get("__pydantic_extra__") is not None:
        value = ts_type(typing.get_args(extra)[1], schema)
        lines.append('    /** By number: "1", "2"... */')
        lines.append(f"    [number: number]: {value};")
    lines.append("    [key: string]: any;")
    lines.append("  }")
    return lines


def generate():
    schema = load_schema()
    lines = [
        "// The program state's types: what HyperDrive sends in `program_state` and",
        "// writes to out/program_state.json.",
        "//",
        "// GENERATED by scripts/gen_state_types.py from src/state_schema.py: change",
        "// that file and run the script, don't edit this one. docs/layout-data.md",
        "// explains the keys.",
        "//",
        "// Every key is optional and may be null, and every object is open (other",
        "// keys are allowed): the state fills up as the application is used.",
        "//",
        "// Global declarations, like hd.d.ts (which uses them for HD.State): a",
        '// TypeScript project gets them with /// <reference path=".../state.d.ts" />.',
        "",
        f"declare namespace {NAMESPACE} {{",
        "  /** A JSON object that is free-form, or whose shape isn't described */",
        "  type Loose = Record<string, any>;",
    ]
    for model in models(schema):
        lines.append("")
        lines += interface(model, schema)
    lines += [
        "",
        "  /** The state's top-level keys */",
        "  type Section = " + " | ".join(json.dumps(name) for name in schema.SECTIONS) + ";",
        "}",
        "",
    ]
    return "\n".join(lines)


def main():
    text = generate()
    if "--check" in sys.argv[1:]:
        try:
            with open(OUT_FILE, encoding="utf-8") as file:
                current = file.read()
        except FileNotFoundError:
            current = None
        if current != text:
            print(
                f"{os.path.relpath(OUT_FILE, ROOT)} is not up to date with src/state_schema.py: "
                "run python scripts/gen_state_types.py"
            )
            return 1
        print(f"{os.path.relpath(OUT_FILE, ROOT)} is up to date")
        return 0
    with open(OUT_FILE, "w", encoding="utf-8", newline="\n") as file:
        file.write(text)
    print(f"Wrote {os.path.relpath(OUT_FILE, ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
